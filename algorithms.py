class SVM:


    def __init__(self, learning_rate=0.001, lambda_param=0.01, n_iterations=1000):
        self.learning_rate = learning_rate
        self.lambda_param = lambda_param
        self.n_iterations = n_iterations
        self.classifiers = []
        self.classes = None

    def _train_binary(self, X, y):

        n_samples, n_features = X.shape
        w = np.zeros(n_features)
        b = 0


        y_ = np.where(y <= 0, -1, 1)

        for _ in range(self.n_iterations):
            for idx, x_i in enumerate(X):
                condition = y_[idx] * (np.dot(x_i, w) - b) >= 1

                if condition:
                    w -= self.learning_rate * (2 * self.lambda_param * w)
                else:
                    w -= self.learning_rate * (2 * self.lambda_param * w - np.dot(x_i, y_[idx]))
                    b -= self.learning_rate * y_[idx]

        return w, b

    def fit(self, X, y):
        self.classes = np.unique(y)


        for c in self.classes:

            y_binary = np.where(y == c, 1, -1)
            w, b = self._train_binary(X, y_binary)
            self.classifiers.append((w, b))

        return self

    def _decision_function(self, X):
        scores = []
        for w, b in self.classifiers:
            score = np.dot(X, w) - b
            scores.append(score)
        return np.array(scores).T

    def predict(self, X):
        scores = self._decision_function(X)
        return self.classes[np.argmax(scores, axis=1)]

    def predict_proba(self, X):

        scores = self._decision_function(X)

        exp_scores = np.exp(scores - np.max(scores, axis=1, keepdims=True))
        probas = exp_scores / np.sum(exp_scores, axis=1, keepdims=True)
        return probas

