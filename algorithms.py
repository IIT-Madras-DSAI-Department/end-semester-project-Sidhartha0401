class PCA:


    def __init__(self, n_components):
        self.n_components = n_components
        self.components = None
        self.mean = None
        self.explained_variance_ratio = None

    def fit(self, X):

        self.mean = np.mean(X, axis=0)
        X_centered = X - self.mean


        cov_matrix = np.cov(X_centered, rowvar=False)


        eigenvalues, eigenvectors = np.linalg.eigh(cov_matrix)


        sorted_indices = np.argsort(eigenvalues)[::-1]
        eigenvalues = eigenvalues[sorted_indices]
        eigenvectors = eigenvectors[:, sorted_indices]


        self.components = eigenvectors[:, :self.n_components]

        total_variance = np.sum(eigenvalues)
        self.explained_variance_ratio = eigenvalues[:self.n_components] / total_variance

        return self

    def transform(self, X):
        X_centered = X - self.mean
        return np.dot(X_centered, self.components)

    def fit_transform(self, X):
        self.fit(X)
        return self.transform(X)
class KNN:


    def __init__(self, k=5, distance_metric='euclidean', weights='uniform'):
        self.k = k
        self.distance_metric = distance_metric
        self.weights = weights
        self.X_train = None
        self.y_train = None

    def _calculate_distance(self, x1, x2):

        if self.distance_metric == 'euclidean':
            return np.sqrt(np.sum((x1 - x2) ** 2))
        elif self.distance_metric == 'manhattan':
            return np.sum(np.abs(x1 - x2))
        elif self.distance_metric == 'cosine':
            dot_product = np.dot(x1, x2)
            norm_x1 = np.linalg.norm(x1)
            norm_x2 = np.linalg.norm(x2)
            return 1 - (dot_product / (norm_x1 * norm_x2))


    def fit(self, X, y):

        self.X_train = X
        self.y_train = y
        return self

    def predict_single(self, x):

        distances = []

        for i, x_train in enumerate(self.X_train):
            dist = self._calculate_distance(x, x_train)
            distances.append((dist, self.y_train[i]))


        distances.sort(key=lambda x: x[0])
        k_nearest = distances[:self.k]


        labels = [label for _, label in k_nearest]
        dists = [dist for dist, _ in k_nearest]


        if self.weights == 'distance':

            weights = [1 / (d + 1e-8) for d in dists]
            weight_dict = {}
            for label, weight in zip(labels, weights):
                if label in weight_dict:
                    weight_dict[label] += weight
                else:
                    weight_dict[label] = weight


            return max(weight_dict.items(), key=lambda x: x[1])[0]

        else:

            return Counter(labels).most_common(1)[0][0]

    def predict(self, X):

        return np.array([self.predict_single(x) for x in X])

    def predict_proba(self, X):

        probabilities = []

        for x in X:
            distances = []


            for i, x_train in enumerate(self.X_train):
                dist = self._calculate_distance(x, x_train)
                distances.append((dist, self.y_train[i]))


            distances.sort(key=lambda x: x[0])
            k_nearest = distances[:self.k]

            labels = [label for _, label in k_nearest]


            label_counts = Counter(labels)
            prob = np.zeros(10)

            for label, count in label_counts.items():
                prob[label] = count / self.k

            probabilities.append(prob)

        return np.array(probabilities)
