class XGBTree:
    def __init__(self, max_depth, delta, gamma, max_thresholds=50):
        self.max_depth = max_depth
        self.delta = delta
        self.gamma = gamma
        self.max_thresholds = max_thresholds
        self.feature_index = None
        self.threshold = None
        self.left_child = None
        self.right_child = None
        self.value = None
        self.gain = -float('inf')

    def fit(self, X, y, grad, hess, feature_indices, current_depth):
        if current_depth == self.max_depth or X.shape[0] <= 1:
            self._set_leaf_value(grad, hess)
            return

        best_gain = -float('inf')
        best_feature_index = None
        best_threshold = None
        Grad_total = np.sum(grad)
        Hess_total = np.sum(hess)

        for feature_index in feature_indices:
            thresholds = np.unique(X[:, feature_index])
            if len(thresholds) > self.max_thresholds:
                q = np.linspace(0.01, 0.99, self.max_thresholds)
                thresholds = np.unique(np.quantile(X[:, feature_index], q))

            for threshold in thresholds:
                left_mask = X[:, feature_index] <= threshold
                right_mask = ~left_mask
                if np.sum(left_mask) < 1 or np.sum(right_mask) < 1:
                    continue

                L_Grad_total = np.sum(grad[left_mask])
                L_Hess_total = np.sum(hess[left_mask])
                R_Grad_total = np.sum(grad[right_mask])
                R_Hess_total = np.sum(hess[right_mask])

                gain = 0.5 * (
                    (L_Grad_total ** 2) / (L_Hess_total + self.delta) +
                    (R_Grad_total ** 2) / (R_Hess_total + self.delta) -
                    (Grad_total ** 2) / (Hess_total + self.delta)
                )

                if gain > best_gain:
                    best_gain = gain
                    best_feature_index = feature_index
                    best_threshold = threshold

        self.gain = best_gain

        if best_gain <= self.gamma:
            self._set_leaf_value(grad, hess)
            return

        self.feature_index = best_feature_index
        self.threshold = best_threshold
        left_mask = X[:, self.feature_index] <= self.threshold
        right_mask = ~left_mask

        self.left_child = XGBTree(self.max_depth, self.delta, self.gamma)
        self.right_child = XGBTree(self.max_depth, self.delta, self.gamma)

        self.left_child.fit(
            X[left_mask], y[left_mask], grad[left_mask], hess[left_mask],
            feature_indices, current_depth + 1
        )
        self.right_child.fit(
            X[right_mask], y[right_mask], grad[right_mask], hess[right_mask],
            feature_indices, current_depth + 1
        )

    def _set_leaf_value(self, grad, hess):
        Grad_total = np.sum(grad)
        Hess_total = np.sum(hess)
        self.value = -Grad_total / (Hess_total + self.delta)

    def predict(self, X):
        if self.value is not None:
            return np.full(X.shape[0], self.value)

        feature = X[:, self.feature_index]
        left_mask = feature <= self.threshold
        right_mask = ~left_mask
        predictions = np.zeros(X.shape[0])

        if np.sum(left_mask) > 0:
            predictions[left_mask] = self.left_child.predict(X[left_mask])
        if np.sum(right_mask) > 0:
            predictions[right_mask] = self.right_child.predict(X[right_mask])
        return predictions

class XGBMultiClassClassifier:
    def __init__(self, n_estimators=100, learning_rate=0.3, delta=1.0, gamma=0,
                 max_depth=6, colsample_bytree=0.1, subsample=0.8):
        self.n_estimators = n_estimators
        self.learning_rate = learning_rate
        self.delta = delta
        self.gamma = gamma
        self.max_depth = max_depth
        self.colsample_bytree = colsample_bytree
        self.subsample = subsample
        self.classifiers = []
        self.n_classes = None

    def softmax(self, x):
        exp_x = np.exp(x - np.max(x, axis=1, keepdims=True))
        return exp_x / np.sum(exp_x, axis=1, keepdims=True)

    def fit(self, X, y):
        self.n_classes = len(np.unique(y))
        self.classifiers = []


        for class_idx in range(self.n_classes):

            y_binary = (y == class_idx).astype(int)

            y_mean = np.mean(y_binary)
            init_pred = np.log(y_mean / (1 - y_mean)) if y_mean not in [0, 1] else 0
            pred = np.full_like(y_binary, fill_value=init_pred, dtype=float)

            n_features_total = X.shape[1]
            X_np = X.values if hasattr(X, 'values') else X

            if self.subsample < 1.0:
                n_samples = int(X.shape[0] * self.subsample)
                sample_indices = np.random.choice(X.shape[0], n_samples, replace=False)
            else:
                sample_indices = np.arange(X.shape[0])

            trees = []

            for i in range(self.n_estimators):
                prob = 1 / (1 + np.exp(-pred[sample_indices]))
                grad = prob - y_binary[sample_indices]
                hess = prob * (1 - prob)
                hess = np.maximum(hess, 1e-6)

                n_features_subsample = int(n_features_total * self.colsample_bytree)
                feature_indices = np.random.choice(
                    n_features_total, size=n_features_subsample, replace=False
                )

                tree = XGBTree(
                    max_depth=self.max_depth,
                    delta=self.delta,
                    gamma=self.gamma
                )
                tree.fit(X_np[sample_indices], y_binary[sample_indices],
                        grad, hess, feature_indices, current_depth=0)

                if tree.gain <= self.gamma and i > 10:
                    break

                update = tree.predict(X_np[sample_indices])
                pred[sample_indices] += self.learning_rate * update
                trees.append(tree)

                if i % 20 == 0:
                    current_prob = 1 / (1 + np.exp(-pred[sample_indices]))
                    current_acc = np.mean((current_prob > 0.5) == y_binary[sample_indices])

            self.classifiers.append({
                'trees': trees,
                'init_pred': init_pred
            })



    def predict_proba(self, X):

        X_np = X.values if hasattr(X, 'values') else X
        n_samples = X.shape[0]


        raw_scores = np.zeros((n_samples, self.n_classes))

        for class_idx in range(self.n_classes):
            classifier = self.classifiers[class_idx]
            pred = np.full(n_samples, classifier['init_pred'])

            for tree in classifier['trees']:
                pred += self.learning_rate * tree.predict(X_np)

            raw_scores[:, class_idx] = pred


        return self.softmax(raw_scores)

    def predict(self, X):

        proba = self.predict_proba(X)
        return np.argmax(proba, axis=1)

